package io.github.nalukit.pololeitest.corpus;

import io.github.nalukit.pololei.Bic;
import io.github.nalukit.pololei.Iban;
import io.github.nalukit.pololei.IbanValidator;
import io.github.nalukit.pololei.NationalCheckMode;
import io.github.nalukit.pololei.ValidationResult;
import io.github.nalukit.pololei.creditor.CreditorIdentifier;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The public corpus: the retained upstream files, the sections of them that contain identifiers
 * ({@code sections.tsv}), and the reviewed expectation for every value ({@code expectations.tsv}).
 * <p>
 * Values are taken from the unchanged files with the pattern of their section; nothing is copied by
 * hand. Expected results are never generated by a test run.
 */
final class Corpus {

  static final Path ROOT = Path.of("src/test/resources/corpus");

  static final String VALID = "VALID";

  /** Upstream statements a section can make about its values. */
  static final Set<String> UPSTREAM = Set.of("valid", "invalid", "experimental", "national-invalid");

  /** Identifier kinds of the corpus. */
  static final Set<String> KINDS = Set.of("IBAN", "BIC", "CI");

  private static final IbanValidator NATIONAL = IbanValidator.standard()
                                                             .nationalCheck(NationalCheckMode.IF_SUPPORTED);

  private Corpus() {
  }

  /** A line range of a retained file and how its values are taken from it. */
  record Section(String file,
                 int firstLine,
                 int lastLine,
                 String kind,
                 String upstream,
                 Pattern pattern,
                 String description) {
  }

  /** One value of a retained file: where it is, what it is, and what the upstream project says. */
  record Value(String file,
               int line,
               String kind,
               String upstream,
               String value) {

    String location() {
      return file + ":" + line;
    }
  }

  /**
   * The reviewed expectation of a value.
   *
   * @param result   pololei with the international rules: {@code VALID} or the error
   * @param national pololei with national check digits ({@code IF_SUPPORTED}): {@code VALID/<status>}
   *                 or the error; {@code -} for BIC and Creditor Identifier
   * @param note     why the result differs from the upstream statement; empty if it does not
   */
  record Expectation(Value value,
                     String result,
                     String national,
                     String note) {
  }

  static List<String[]> table(String name) {
    try {
      List<String> lines = Files.readAllLines(ROOT.resolve(name), StandardCharsets.UTF_8);
      int columns = lines.getFirst()
                         .split("\t", -1).length;
      List<String[]> rows = new ArrayList<>();
      for (String line : lines.subList(1, lines.size())) {
        if (line.isEmpty()) {
          continue;
        }
        String[] row = line.split("\t", -1);
        if (row.length != columns) {
          throw new IllegalStateException(name + ": " + columns + " columns expected: " + line);
        }
        rows.add(row);
      }
      return rows;
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  static List<Section> sections() {
    return table("sections.tsv").stream()
                                .map(row -> new Section(row[0],
                                                        Integer.parseInt(row[1]),
                                                        Integer.parseInt(row[2]),
                                                        row[3],
                                                        row[4],
                                                        Pattern.compile(row[5]),
                                                        row[6]))
                                .toList();
  }

  /** All values of all sections, in the order of {@code sections.tsv} and of the lines. */
  static List<Value> extract() {
    List<Value> values = new ArrayList<>();
    for (Section section : sections()) {
      List<String> lines = lines(section.file());
      for (int line = section.firstLine(); line <= section.lastLine(); line++) {
        Matcher matcher = section.pattern()
                                 .matcher(lines.get(line - 1));
        while (matcher.find()) {
          values.add(new Value(section.file(), line, section.kind(), section.upstream(), matcher.group(1)));
        }
      }
    }
    return values;
  }

  static List<String> lines(String file) {
    try {
      return Arrays.asList(Files.readString(ROOT.resolve(file), StandardCharsets.UTF_8)
                                .split("\n", -1));
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }

  static List<Expectation> expectations() {
    return table("expectations.tsv").stream()
                                    .map(row -> new Expectation(new Value(row[0], Integer.parseInt(row[1]), row[2], row[3], row[4]),
                                                                row[5],
                                                                row[6],
                                                                row[7]))
                                    .toList();
  }

  /** The result of pololei with the international rules. */
  static String result(String kind,
                       String value) {
    return switch (kind) {
      case "IBAN" -> describe(Iban.validate(value));
      case "BIC" -> describe(Bic.validate(value));
      case "CI" -> CreditorIdentifier.validate(value)
                                     .map(Enum::name)
                                     .orElse(VALID);
      default -> throw new IllegalArgumentException("unknown kind " + kind);
    };
  }

  /** The result of pololei with national check digits where a rule exists. */
  static String national(String kind,
                         String value) {
    if (!kind.equals("IBAN")) {
      return "-";
    }
    ValidationResult<Iban, ?> result = NATIONAL.validate(value);
    return result.isValid() ? VALID + "/" + result.nationalCheck() : describe(result);
  }

  private static String describe(ValidationResult<?, ?> result) {
    return result.isValid() ? VALID : result.error()
                                            .orElseThrow()
                                            .name();
  }

  /** Whether the pololei result is what the upstream project states. */
  static boolean agrees(Expectation expectation) {
    return switch (expectation.value()
                              .upstream()) {
      case "valid" -> expectation.result()
                                 .equals(VALID);
      case "invalid", "experimental" -> !expectation.result()
                                                    .equals(VALID);
      case "national-invalid" -> expectation.result()
                                            .equals(VALID) && expectation.national()
                                                                         .equals("INVALID_NATIONAL_CHECK_DIGITS");
      default -> throw new IllegalArgumentException("unknown upstream statement " + expectation.value()
                                                                                             .upstream());
    };
  }

  /**
   * Whether the expectation must explain itself: the result differs from the upstream statement, or
   * an IBAN the upstream project calls valid fails its national check digits.
   */
  static boolean needsNote(Expectation expectation) {
    return !agrees(expectation) || expectation.value()
                                              .upstream()
                                              .equals("valid") && expectation.value()
                                                                             .kind()
                                                                             .equals("IBAN") && !expectation.national()
                                                                                                            .startsWith(VALID);
  }
}
